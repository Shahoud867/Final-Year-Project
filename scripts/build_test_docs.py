"""Test documentation from the tests themselves.

    python scripts/build_test_docs.py            # rewrite docs/manuals/system-test-cases.md from the test docstrings
    python scripts/build_test_docs.py --check    # exit 1 if that file is out of date
    python scripts/build_test_docs.py --run      # run every suite and write evidence/reports/<date>_test-results.md

The catalogue is generated from tests/system/test_system.py, so a documented test case is always an executable
one. The results record is produced by actually running the suites (JUnit XML and coverage JSON are parsed); it
states the commit and whether the working tree had uncommitted changes.
"""

from __future__ import annotations

import ast
import datetime as dt
import json
import re
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SYSTEM_TESTS = ROOT / "tests" / "system" / "test_system.py"
CATALOGUE = ROOT / "docs" / "manuals" / "system-test-cases.md"
GROUPS = {"SYS-CORE": "Investigation journeys", "SYS-ERR": "Failure and edge cases", "SYS-SEC": "Security", "SYS-REL": "Reliability"}
NL = chr(10)


def cases() -> list[dict[str, str]]:
    """Parse the test-case specifications out of the docstrings of the system tests."""
    out = []
    tree = ast.parse(SYSTEM_TESTS.read_text(encoding="utf-8"))
    for node in tree.body:
        if not isinstance(node, ast.FunctionDef) or not node.name.startswith("test_sys_"):
            continue
        doc = ast.get_docstring(node) or ""
        head, *rest = [ln.strip() for ln in doc.split(NL) if ln.strip()]
        match = re.match(r"(SYS-[A-Z]+-[0-9]+) (.+)", head)
        if not match:
            raise SystemExit(f"{node.name}: the docstring must start with an id and a title, for example 'SYS-CORE-01 Title'")
        fields = {"id": match.group(1), "title": match.group(2).rstrip("."), "function": node.name,
                  "own_server": "yes" if any(getattr(d, "id", "") == "own_server" for d in node.decorator_list) else "no"}
        for line in rest:
            key, _, value = line.partition(":")
            if key in ("Requirement", "Steps", "Expected"):
                fields[key.lower()] = value.strip()
        missing = [k for k in ("requirement", "steps", "expected") if not fields.get(k)]
        if missing:
            raise SystemExit(f"{node.name}: the docstring is missing {missing}")
        out.append(fields)
    ids = [c["id"] for c in out]
    if len(set(ids)) != len(ids):
        raise SystemExit("duplicate test-case ids in tests/system")
    return out


def catalogue() -> str:
    all_cases = cases()
    lines = [
        "# System test cases", "",
        "Generated by `python scripts/build_test_docs.py` from the docstrings of "
        "[`tests/system/test_system.py`](../../tests/system/test_system.py). Do not edit by hand: every case below is an "
        "executable test, and CI fails if this file is out of date.", "",
        "**Level:** system (black box). The suite starts the real server as a separate process and uses only HTTP, the "
        "way the web UI or a script reaches it. Model answers come from the recorded cassette, so results are "
        "deterministic and need no model. Unit and integration tests live next to the code they test "
        "(`packages/*/tests`, `workflows/*/tests`, `apps/api/tests`, `apps/web/tests`).", "",
        "**Run:** `pytest tests/system` from the repository root. To test a server that is already running (a container "
        "or a deployed instance): `GRANITE_SYSTEM_BASE_URL=https://host pytest tests/system`; cases marked *own server* "
        "need to configure the server themselves and are then skipped.", "",
        f"**Cases:** {len(all_cases)} in {len(GROUPS)} groups. Latest recorded results: see `evidence/reports/`.", "",
    ]
    for prefix, title in GROUPS.items():
        group = [c for c in all_cases if c["id"].startswith(prefix)]
        lines += [f"## {prefix}: {title}", "", "| ID | Test case | Requirement | Steps | Expected result | Own server |", "|---|---|---|---|---|---|"]
        for c in group:
            lines.append(f"| {c['id']} | {c['title']} | {c['requirement']} | {c['steps']} | {c['expected']} | {c['own_server']} |")
        lines.append("")
    lines += ["## Mapping to the executable tests", "", "| ID | Test function |", "|---|---|"]
    lines += [f"| {c['id']} | `{c['function']}` |" for c in all_cases]
    return NL.join(lines) + NL


# ---- running the suites -----------------------------------------------------------------------------------
PY_SUITES = [
    ("Core library (unit, property)", "packages/granite_core", ["tests"], "granite_core"),
    ("Refund Desk workflow (unit, integration)", "workflows/refund_desk", ["tests"], "refund_desk"),
    ("API (integration, recorded model)", "apps/api", ["tests"], "granite_api"),
    ("System (black box over HTTP)", ".", ["tests/system"], ""),
]


def _run(cmd: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, encoding="utf-8", errors="replace", check=False)  # noqa: S603


def _git(*args: str) -> str:
    return _run(["git", *args], ROOT).stdout.strip()


def run_all() -> str:
    tmp = Path(tempfile.mkdtemp(prefix="granite-tests-"))
    rows, sys_status = [], {}
    total = failed = 0
    for i, (name, folder, paths, cov) in enumerate(PY_SUITES):
        junit, cov_json = tmp / f"junit{i}.xml", tmp / f"cov{i}.json"
        cmd = [sys.executable, "-m", "pytest", *paths, "-q", "-p", "no:cacheprovider", "-o", "addopts=", f"--junitxml={junit}"]
        if cov:
            cmd += [f"--cov={cov}", f"--cov-report=json:{cov_json}", "--cov-report="]
        proc = _run(cmd, ROOT / folder)
        suite = ET.parse(junit).getroot()
        suite = suite if suite.tag == "testsuite" else suite[0]
        n, bad, skipped = int(suite.get("tests", 0)), int(suite.get("failures", 0)) + int(suite.get("errors", 0)), int(suite.get("skipped", 0))
        coverage = f"{json.loads(cov_json.read_text(encoding='utf-8'))['totals']['percent_covered']:.1f}%" if cov and cov_json.exists() else "n/a"
        rows.append(f"| {name} | `{' '.join(paths)}` in `{folder}` | {n} | {n - bad - skipped} | {bad} | {skipped} | {coverage} | {float(suite.get('time', 0)):.1f} s |")
        total, failed = total + n, failed + bad
        if not cov:
            for case in suite.iter("testcase"):
                state = "FAIL" if case.find("failure") is not None or case.find("error") is not None else ("skipped" if case.find("skipped") is not None else "pass")
                sys_status[case.get("name", "")] = state
        if proc.returncode not in (0, 1):
            raise SystemExit(f"{name}: pytest could not run:{NL}{proc.stdout[-800:]}{proc.stderr[-800:]}")
    web = ROOT / "apps" / "web"
    npx = shutil.which("npx") or "npx"
    out = tmp / "vitest.json"
    _run([npx, "vitest", "run", "--reporter=json", f"--outputFile={out}"], web)
    v = json.loads(out.read_text(encoding="utf-8"))
    rows.append(f"| Web UI (component, accessibility) | `tests` in `apps/web` | {v['numTotalTests']} | {v['numPassedTests']} | {v['numFailedTests']} | "
                f"{v.get('numPendingTests', 0)} | n/a | n/a |")
    total, failed = total + v["numTotalTests"], failed + v["numFailedTests"]

    today = dt.date.today().isoformat()
    dirty = bool(_git("status", "--porcelain"))
    lines = [
        f"# Test results, {today}", "",
        "Produced by `python scripts/build_test_docs.py --run`, which executes every suite and parses the JUnit and "
        "coverage output. Nothing in this file is typed by hand.", "",
        "| | |", "|---|---|",
        f"| Commit | `{_git('rev-parse', '--short', 'HEAD')}` on `{_git('rev-parse', '--abbrev-ref', 'HEAD')}`"
        f"{' **plus uncommitted changes in the working tree**' if dirty else ' (clean working tree)'} |",
        f"| Python | {sys.version.split()[0]} on {sys.platform} |",
        f"| Result | **{total - failed} of {total} tests passed**{'' if not failed else f'; {failed} FAILED'} |", "",
        "## Suites", "", "| Suite (level) | Location | Tests | Passed | Failed | Skipped | Line coverage | Time |", "|---|---|---|---|---|---|---|---|",
        *rows, "",
        "Coverage is line coverage of the package under test, measured by its own suite. Tests and code were written by the "
        "same author, so coverage shows the code does what was intended, not that the intent is right.", "",
        "## System test cases", "", "| ID | Test case | Result |", "|---|---|---|",
    ]
    for c in cases():
        lines.append(f"| {c['id']} | {c['title']} | {sys_status.get(c['function'], 'not run')} |")
    lines += ["", "Specifications of these cases (steps and expected results): "
              "[`docs/manuals/system-test-cases.md`](../../docs/manuals/system-test-cases.md).", ""]
    target = ROOT / "evidence" / "reports" / f"{today}_test-results.md"
    target.write_text(NL.join(lines), encoding="utf-8", newline=NL)
    shutil.rmtree(tmp, ignore_errors=True)
    print(f"wrote {target.relative_to(ROOT).as_posix()}: {total - failed}/{total} passed")
    return "ok" if not failed else "failed"


def main() -> int:
    text = catalogue()
    if "--check" in sys.argv:
        ok = CATALOGUE.exists() and CATALOGUE.read_text(encoding="utf-8") == text
        print("system test catalogue up to date" if ok else "docs/manuals/system-test-cases.md is out of date; run scripts/build_test_docs.py")
        return 0 if ok else 1
    CATALOGUE.write_text(text, encoding="utf-8", newline=NL)
    print(f"wrote {CATALOGUE.relative_to(ROOT).as_posix()}: {len(cases())} cases")
    if "--run" in sys.argv:
        return 0 if run_all() == "ok" else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
