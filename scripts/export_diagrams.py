"""Generate the diagrams that must always match the code, as Mermaid inside Markdown files.

    python scripts/export_diagrams.py          # rewrite docs/diagrams/finding-state-machine.md and refund-desk-dataflow.md
    python scripts/export_diagrams.py --check  # exit 1 if a committed diagram differs from what the code produces
"""

from __future__ import annotations

import sys
from pathlib import Path

from granite_api.db import Base
from granite_api.models import Run  # noqa: F401  (importing the models registers the tables)
from granite_core.lifecycle import TERMINAL, TRANSITIONS, FindingStatus
from refund_desk import build_workflow

OUT = Path(__file__).resolve().parents[1] / "docs" / "diagrams"
NOTE = "Generated by `python scripts/export_diagrams.py` from the code. Do not edit by hand; a CI check fails if it drifts."


def state_machine() -> str:
    lines = ["stateDiagram-v2", f"    [*] --> {FindingStatus.OPEN.value}"]
    for (src, event), dst in TRANSITIONS.items():
        lines.append(f"    {src.value} --> {dst.value}: {event.value}")
    lines += [f"    {s.value} --> [*]" for s in sorted(TERMINAL, key=lambda s: s.value)]
    body = "\n".join(lines)
    return (
        "# Finding state machine\n\n"
        f"{NOTE}\n\n"
        "Every change of a finding's status goes through `granite_core.lifecycle.transition`; an event that is not "
        "listed here for the current status raises an error and the API answers 409 with the allowed actions. "
        "The levels V0 to V3 follow from the status (`verification_level`).\n\n"
        f"```mermaid\n{body}\n```\n"
    )


def dataflow() -> str:
    defn = build_workflow()
    lines = ["flowchart LR", "    task([Task input])"]
    for s in defn.steps:
        lines.append(f'    {s.step_id}["{s.step_id} {s.agent}<br/>{s.kind}"]')
    for s in defn.steps:
        for ref in s.reads:
            src, field = ref.split(".", 1)
            lines.append(f"    {'task' if src == 'task' else src} -->|{field}| {s.step_id}")
    checks = "\n".join(f"- `{c.id}` ({c.scope}, {c.type}) on {c.step}: {c.name}" for c in defn.checks)
    return (
        "# Refund Desk data flow\n\n"
        f"{NOTE}\n\n"
        "Edges are the `reads` each step declares; the runner records them and attribution walks them backwards. "
        "A stale price enters at s2 and travels s2 to s3 to s4 to s5.\n\n"
        f"```mermaid\n{chr(10).join(lines)}\n```\n\n## Checks\n\n{checks}\n"
    )


def er_diagram() -> str:
    nl = chr(10)
    lines = ["erDiagram"]
    for table in Base.metadata.sorted_tables:
        for fk in table.foreign_keys:
            lines.append(f"    {fk.column.table.name} ||--o{{ {table.name} : {fk.parent.name}")
    for table in Base.metadata.sorted_tables:
        lines.append(f"    {table.name} {{")
        for col in table.columns:
            kind = str(col.type).split("(")[0].replace(" ", "_") or "TEXT"
            key = " PK" if col.primary_key else (" FK" if col.foreign_keys else "")
            lines.append(f"        {kind} {col.name}{key}")
        lines.append("    }")
    intro = (
        "Evidence and audit rows are append-only (the API has no update or delete route for them). The canonical "
        "trace of a run is the JSON column `runs.trace`; steps and graph edges are derived from it "
        "([ADR-003](../adr/adr-003-persistence-sqlalchemy.md)). `evidence` and `audit_log` carry ids without foreign "
        "keys on purpose, so they outlive the rows they describe."
    )
    body = nl.join(lines)
    return f"# Database schema{nl}{nl}{NOTE}{nl}{nl}{intro}{nl}{nl}```mermaid{nl}{body}{nl}```{nl}"


def main() -> int:
    files = {"finding-state-machine.md": state_machine(), "refund-desk-dataflow.md": dataflow(),
             "database-schema.md": er_diagram()}
    if "--check" in sys.argv:
        bad = [n for n, t in files.items() if not (OUT / n).exists() or (OUT / n).read_text(encoding="utf-8") != t]
        print("diagrams up to date" if not bad else f"out of date: {', '.join(bad)}")
        return 1 if bad else 0
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        print("wrote", OUT / name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
