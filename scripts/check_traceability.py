"""Requirements traceability: requirement (master plan) -> implementation -> tests, checked against the repository.

    python scripts/check_traceability.py          # validate, then rewrite docs/plan/requirements-trace.md
    python scripts/check_traceability.py --check  # validate and fail if the generated file is out of date

Fails if a Mid-1 requirement of the plan has no entry in requirements-trace.json, an entry names an unknown
requirement, a referenced file does not exist, or a referenced function or test title is not in its file.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLAN = ROOT / "docs" / "plan" / "master-plan.md"
DATA = ROOT / "docs" / "plan" / "requirements-trace.json"
OUT = ROOT / "docs" / "plan" / "requirements-trace.md"
NL, DOT = chr(10), chr(0xB7)
LINE = re.compile(r"^- [*][*](FR-[A-Z]+-[0-9]+)[*][*] (.*)$")
STATUS_ORDER = ["done", "partial", "not-met"]


def plan_requirements() -> dict[str, dict[str, object]]:
    found: dict[str, dict[str, object]] = {}
    for line in PLAN.read_text(encoding="utf-8").split(NL):
        m = LINE.match(line)
        if not m:
            continue
        parts = [p.strip() for p in m.group(2).split(DOT)]
        priority = parts[1] if len(parts) > 1 else ""
        milestone = parts[2] if len(parts) > 2 else ""
        found[m.group(1)] = {
            "text": parts[0],
            "priority": priority,
            "milestone": milestone if milestone else priority,
            "mid1": "Mid-1" in priority or milestone.startswith("Mid-1"),
        }
    return found


def check_ref(ref: str) -> str | None:
    path, _, name = ref.partition("::")
    target = ROOT / path
    if not target.is_file():
        return f"missing file: {path}"
    if name and name not in target.read_text(encoding="utf-8"):
        return f"'{name}' not found in {path}"
    return None


def link(ref: str) -> str:
    path, _, name = ref.partition("::")
    label = f"{path.rsplit('/', 1)[-1]}::{name}" if name else path.rsplit("/", 1)[-1]
    return f"[{label}](../../{path})"


def short(text: str, limit: int = 110) -> str:
    text = text.replace("|", "/")
    return text if len(text) <= limit else text[: limit - 1] + "..."


def build(reqs: dict[str, dict[str, object]], data: dict[str, dict[str, object]]) -> tuple[str, list[str]]:
    errors = [f"{i}: Mid-1 requirement has no entry in requirements-trace.json" for i, r in reqs.items() if r["mid1"] and i not in data]
    errors += [f"{i}: not a requirement of the plan" for i in data if i not in reqs]
    for i, entry in data.items():
        for ref in [*entry.get("impl", []), *entry.get("tests", [])]:  # type: ignore[union-attr]
            problem = check_ref(str(ref))
            if problem:
                errors.append(f"{i}: {problem}")
        if entry.get("status") not in STATUS_ORDER:
            errors.append(f"{i}: status must be one of {STATUS_ORDER}")
        if not entry.get("tests"):
            errors.append(f"{i}: no test is listed")
    mid1 = {i: r for i, r in reqs.items() if r["mid1"]}
    counts = {s: sum(1 for i in mid1 if data.get(i, {}).get("status") == s) for s in STATUS_ORDER}
    lines = [
        "# Requirements traceability (functional requirements, Mid-1)", "",
        "Generated by `python scripts/check_traceability.py` from the plan's requirement list and "
        "[`requirements-trace.json`](requirements-trace.json). The script fails if a Mid-1 requirement is missing, a file "
        "or test it names does not exist, or this file is out of date. It proves the references are real, **not that "
        "the tests are sufficient**; read the Note column for gaps.", "",
        f"Mid-1 requirements: {len(mid1)}. Done: {counts['done']}. Partly met: {counts['partial']}. "
        f"Not met: {counts['not-met']}.", "",
        "| ID | Requirement | Status | Implementation | Tests | Note |", "|---|---|---|---|---|---|",
    ]
    for i, r in mid1.items():
        e = data.get(i, {})
        impl = "<br>".join(link(str(x)) for x in e.get("impl", []))  # type: ignore[union-attr]
        tests = "<br>".join(link(str(x)) for x in e.get("tests", []))  # type: ignore[union-attr]
        lines.append(f"| {i} | {short(str(r['text']))} | **{e.get('status', 'missing')}** | {impl} | {tests} | {short(str(e.get('note', '')), 200)} |")
    later = {i: r for i, r in reqs.items() if not r["mid1"]}
    lines += ["", "## Later milestones (not part of Mid-1)", "", "| ID | Requirement | When |", "|---|---|---|"]
    lines += [f"| {i} | {short(str(r['text']), 90)} | {short(str(r['milestone']), 40)} |" for i, r in later.items()]
    return NL.join(lines) + NL, errors


def main() -> int:
    reqs = plan_requirements()
    data = json.loads(DATA.read_text(encoding="utf-8"))
    text, errors = build(reqs, data)
    for e in errors:
        print("ERROR:", e)
    if errors:
        return 1
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("traceability up to date" if ok else "requirements-trace.md is out of date; run scripts/check_traceability.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline=NL)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(reqs)} requirements, {sum(1 for r in reqs.values() if r['mid1'])} for Mid-1")
    return 0


if __name__ == "__main__":
    sys.exit(main())
