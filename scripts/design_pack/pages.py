def _index(sheets: list[Sheet], page_of: dict[str, str]) -> str:
    by_key = {s.key: s for s in sheets}
    covered = {k for _, _, keys, _ in TABLE_1A for k in keys}
    if covered != set(by_key):
        raise SystemExit(f"design pack index is out of date: {sorted(covered ^ set(by_key))}")
    lines = [
        "# Design pack (Iteration 1)", "", NOTE, "",
        f"{len(sheets)} diagrams and a data dictionary cover every design artefact that handbook Table 1a lists for the "
        "FYP-1 mid evaluation. They are drawn by a small generator in `scripts/design_pack/` so that one visual style is "
        "used throughout and so that facts come from the code: tables, columns and keys from the database models; "
        "states and events from the lifecycle module; steps, reads and checks from the workflow definition; call edges "
        "from static analysis of the source; verdict regions and worked examples by calling the real functions on a "
        "recorded run. A layout lint rejects overlapping boxes, text that overflows, and connectors through boxes.", "",
        "**Interactive version:** [`granite_design-pack_fyp1-mid_v1.0.html`](../../deliverables/stage-1-fyp1-mid/granite_design-pack_fyp1-mid_v1.0.html) "
        "(one self-contained file: navigation, search, zoom, and click a box to highlight what it connects to).", "",
        "## Handbook Table 1a coverage", "",
        "| Table 1a group | Required artefact | Provided | Notes |", "|---|---|---|---|",
    ]
    for group, item, keys, note in TABLE_1A:
        links = "<br>".join(f"[{by_key[k].diagram.title}]({page_of[k]}) ([svg]({k}.svg))" for k in keys)
        lines.append(f"| {group} | {item} | {links or 'document'} | {note} |")
